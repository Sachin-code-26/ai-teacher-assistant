// =============================================================
//  server/models/Evaluation.js
//
//  Stores the AI-generated grade AND the teacher's final override.
//
//  IMPORTANT DESIGN PRINCIPLE:
//  We NEVER overwrite the AI's original scores.
//  The AI result is stored as-is, and the teacher override
//  is stored in SEPARATE fields (teacherFinalMarks, teacherComments).
//
//  This means we always have a full audit trail:
//  "The AI gave 7/10. The teacher changed it to 8/10 because..."
//
//  The `criteriaResults` array mirrors the assignment's rubric.
//  For each rubric criterion, the AI provides:
//  - How many marks it awarded (marksAwarded)
//  - Why it gave that score (feedback)
// =============================================================

import mongoose from "mongoose";

// =============================================================
//  CRITERIA RESULT SUB-SCHEMA
//
//  One entry per rubric criterion.
//  The AI fills this in for each criterion in the rubric.
//
//  Example:
//  {
//    criterion: "Understanding of Concept",
//    maxMarks: 5,
//    marksAwarded: 4,
//    feedback: "Good explanation but missed the edge case."
//  }
// =============================================================
const criteriaResultSchema = new mongoose.Schema(
  {
    criterion: {
      type: String,
      required: true,
    },
    maxMarks: {
      type: Number,
      required: true,
      min: 0,
    },
    marksAwarded: {
      type: Number,
      required: true,
      min: 0,
      // Note: We validate marksAwarded <= maxMarks in the grading service,
      // not here, because the max depends on the rubric (another document).
    },
    feedback: {
      type: String,
      required: true,
    },
  },
  { _id: false }
);

// =============================================================
//  EVALUATION SCHEMA
// =============================================================
const evaluationSchema = new mongoose.Schema(
  {
    // The submission this evaluation belongs to
    submissionId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Submission",
      required: true,
      unique: true,          // One evaluation per submission only
    },

    // Denormalized for convenience — lets us query "all evaluations for assignment X"
    // without joining through Submission
    assignmentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Assignment",
      required: true,
    },

    studentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },

    // ── AI-GENERATED RESULTS ────────────────────────────────
    // Array of results, one entry per rubric criterion
    criteriaResults: {
      type: [criteriaResultSchema],
      required: true,
    },

    // Total marks awarded by AI (sum of all criteriaResults.marksAwarded)
    totalMarks: {
      type: Number,
      required: true,
      min: 0,
    },

    // Maximum possible marks for the assignment
    maxMarks: {
      type: Number,
      required: true,
      min: 0,
    },

    // Calculated as (totalMarks / maxMarks) * 100
    percentage: {
      type: Number,
      required: true,
      min: 0,
      max: 100,
    },

    // AI's summary of what the student did well
    strengths: {
      type: [String],
      default: [],
    },

    // AI's summary of what the student could improve
    weaknesses: {
      type: [String],
      default: [],
    },

    // AI's overall narrative feedback
    overallFeedback: {
      type: String,
      required: true,
    },

    // Flag: was this evaluation generated by AI (true) or manually entered (false)?
    aiGenerated: {
      type: Boolean,
      default: true,
    },

    // When the AI generated this evaluation
    evaluatedAt: {
      type: Date,
      default: Date.now,
    },

    // ── TEACHER OVERRIDE FIELDS ─────────────────────────────
    // These are SEPARATE from the AI fields above.
    // They only get populated when a teacher reviews the submission.

    // The teacher's final mark (can differ from AI's totalMarks)
    teacherFinalMarks: {
      type: Number,
      min: 0,
      default: null,
    },

    // Teacher's written comment/justification
    teacherComments: {
      type: String,
      default: null,
    },

    // When the teacher reviewed/overrode the grade
    reviewedAt: {
      type: Date,
      default: null,
    },

    // Which teacher reviewed it
    reviewedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
  },
  {
    timestamps: true,
  }
);

// =============================================================
//  VIRTUAL: finalMarks
//
//  Returns the "effective" final mark:
//  - If a teacher has overridden → use teacher's mark
//  - Otherwise → use AI's totalMarks
//
//  The frontend uses this to display the authoritative score.
//  Usage: evaluation.finalMarks
// =============================================================
evaluationSchema.virtual("finalMarks").get(function () {
  return this.teacherFinalMarks !== null ? this.teacherFinalMarks : this.totalMarks;
});

// Indexes for common query patterns
evaluationSchema.index({ assignmentId: 1 });
evaluationSchema.index({ studentId: 1 });

const Evaluation = mongoose.model("Evaluation", evaluationSchema);

export default Evaluation;
